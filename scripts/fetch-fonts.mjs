// Downloads the brand fonts from Google Fonts (OFL) as woff2 and writes
// src/assets/css/fonts.css with @font-face rules (latin + latin-ext only).
// Run once: node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from 'node:fs/promises';

const FAMILIES = [
  { css: 'Instrument+Serif:ital@0;1', id: 'instrument-serif' },
  { css: 'Space+Grotesk:wght@300;400;500', id: 'space-grotesk' },
  { css: 'IBM+Plex+Mono:wght@400;500', id: 'ibm-plex-mono' },
];
const SUBSETS = new Set(['latin', 'latin-ext']);
const UA = 'Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36';
const OUT_DIR = 'src/assets/fonts';

await mkdir(OUT_DIR, { recursive: true });
const rules = [];

for (const fam of FAMILIES) {
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${fam.css}&display=swap`, { headers: { 'User-Agent': UA } })).text();
  const blocks = css.split('/* ').slice(1);
  for (const block of blocks) {
    const subset = block.slice(0, block.indexOf(' */'));
    if (!SUBSETS.has(subset)) continue;
    const family = block.match(/font-family: '([^']+)'/)[1];
    const style = block.match(/font-style: (\w+)/)[1];
    const weight = block.match(/font-weight: (\d+)/)[1];
    const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
    const range = block.match(/unicode-range: ([^;]+);/)[1];
    const file = `${fam.id}-${weight}${style === 'italic' ? 'i' : ''}-${subset}.woff2`;
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    await writeFile(`${OUT_DIR}/${file}`, buf);
    rules.push(`@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:url('/assets/fonts/${file}') format('woff2');unicode-range:${range};}`);
    console.log('ok', file, buf.length);
  }
}

await writeFile('src/assets/css/fonts.css', `/* generated by scripts/fetch-fonts.mjs — Google Fonts, SIL OFL */\n${rules.join('\n')}\n`);
console.log('fonts.css', rules.length, 'faces');
